function dedupeClean(list) {
  const seen = new Set();
  const out = [];
  for (const line of list) {
    const s = line.trim();
    if (!s || seen.has(s)) continue;
    if (s.length < 8 || s.length > 48) continue;
    if (!/[\u4e00-\u9fff]/.test(s)) continue;
    if (!/[。！？；]$/.test(s)) continue;
    seen.add(s);
    out.push(s);
  }
  return out;
}

